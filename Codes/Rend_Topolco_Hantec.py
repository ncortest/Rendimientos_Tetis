# Function to extract information from the computer

def info_pc(info_equipo, carac):
    # Search the entire DataFrame to see if it contains the text “Processor name:
    mask = info_equipo.apply(lambda row: row.astype(str).str.contains(carac)).any(axis=1)

    # Obtain the indexes (positions) where it was found
    indices = info_equipo[mask].index.tolist()

    variable = info_equipo.iloc[indices[0], 1]
    
    return variable


