# Function to replace scale data
def replace_scale(vec):
    if "1k" in vec:
        vec = "1000"
    elif "2p5" in vec:
        vec = "2500"
    elif "5k" in vec:
        vec = "5000"
    elif "30m" in vec:
        vec = "30"
    elif "200m" in vec:
        vec = "200"
    elif "500m" in vec:
        vec = "500"
    return vec

################################################################################
# Function to set the current time
def def_hora():
    return time.strftime("%d-%m-%Y %H:%M:%S", time.localtime())

################################################################################
def leer_ultima_frecuencia(hwinfo_log_path, freq_col_name):
    """
    Read the latest available frequency from the HWiNFO in monitor.csv file.
    """
    try:
        with open(hwinfo_log_path, 'r', encoding='utf-8', errors='ignore') as f:
            reader = csv.DictReader(f)
            last_row = None
            for row in reader:
                if row[freq_col_name]:
                    last_row = row
        if last_row:
            valor = last_row[freq_col_name].replace(",", ".").strip()
            return float(valor)
    except Exception:
        return None 
    
################################################################################
# Function to run an .exe and measure the time
def run_exe_monitor(exe_name, path_model, hwinfo_log_path, freq_col_name):
    """
    Run an executable and measure the execution time, as well as the average processor frequency.

    Parameters:
    - exe_name: name of the executable file (e.g., “Toparc.exe”)
    - path_model: path to the directory where the executable is located
    - hwinfo_log_path: full path to the .csv file generated by HWiNFO
    - freq_col_name: exact name of the column containing the frequency in MHz

    Returns:
    - Dictionary with times and average frequency
    """
    print("Starting monitoring and execution of the process...")
    try:
        freq_values = []
    
        os.chdir(path_model)
        process = subprocess.Popen([exe_name])
    
        start_time = time.time()
    
        while process.poll() is None:
            freq_now = leer_ultima_frecuencia(hwinfo_log_path, freq_col_name)
            if freq_now:
                freq_values.append(freq_now)
                print(f"{time.strftime('%H:%M:%S')} - Frequency: {freq_now:.2f} MHz")
            time.sleep(1)
    
        end_time = time.time()
    
        exec_time = end_time - start_time #Calcula el tiempo total de ejecución
        freq_promedio = (sum(freq_values) / len(freq_values))/1000 if freq_values else float('nan') #Calcula el promedio de velocidad del procesador
    
        days = exec_time // 86400
        hours = (exec_time % 86400) // 3600
        minutes = (exec_time % 3600) // 60
        seconds = round(exec_time % 60, 1)
        total_days = exec_time / 86400
        total_hours = exec_time / 3600
        total_minutes = exec_time / 60
        
        return exec_time, days, hours, minutes, seconds, total_days, total_hours, total_minutes, freq_promedio
    
    except Exception as e:
        
        print(f"Error while executing the process: {e}")
        # Retornar un conjunto de valores indicativos
        return tuple(["NOT EXECUTABLE"] * 9)
    
